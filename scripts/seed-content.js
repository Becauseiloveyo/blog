function ensureCategory(name, slug, description, color) {
  const existing = db.prepare('SELECT id FROM categories WHERE slug = ?').get(slug);
  if (existing) {
    db.prepare('UPDATE categories SET name = ?, description = ?, color = ? WHERE slug = ?').run(name, description, color, slug);
    return existing.id;
  }
  const info = db.prepare('INSERT INTO categories (name, slug, description, color) VALUES (?, ?, ?, ?)').run(name, slug, description, color);
  return info.lastInsertRowid;
}

